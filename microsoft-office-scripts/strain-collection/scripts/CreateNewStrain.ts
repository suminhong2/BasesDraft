// Create a new strain from your own lab
// Reads section 1 of the Forms tab, gives the strain(s) the next numbers (REC1, REC2...)
// and, if a strain type is chosen, the next allele / transgene name (vrt1, vrtEx1...).
function main(workbook: ExcelScript.Workbook) {
  const result = named(workbook, "NS_Result");
  try {
    result.setValue("✓ " + createStrains(workbook));
    clearForm(workbook, ["NS_Type", "NS_Alleles", "NS_Background", "NS_DNA", "NS_Notes",
      "NS_Maintenance", "NS_Available", "NS_Location"]);
    named(workbook, "NS_Quantity").setValue(1);
  } catch (e) {
    const reason = String(e).replace(/^Error: /, "");
    result.setValue("✗ " + reason);
    // Also fail the run, so the Automate pane / button shows the reason instead of "complete"
    throw new Error(reason);
  }
}

function createStrains(workbook: ExcelScript.Workbook): string {
  const quantity = Number(read(workbook, "NS_Quantity")) || 1;
  if (quantity < 1 || quantity > 100 || Math.floor(quantity) !== quantity) {
    throw new Error("Number of strains must be a whole number from 1 to 100.");
  }
  const author = read(workbook, "NS_GeneratedBy");
  if (!author) throw new Error("Fill in Generated by.");
  const labCode = read(workbook, "LabCode");
  const alleleCode = read(workbook, "AlleleCode");
  const nextStrain = Number(read(workbook, "NextStrain"));
  if (!labCode) throw new Error("Fill in the Lab code on the Settings tab.");
  if (!(nextStrain > 0)) throw new Error("Next strain number on the Settings tab is not a number.");

  // Make sure none of the new names exists already
  const strains = table(workbook, "StrainTable");
  const existing = columnValues(strains, "Strain number").map(n => n.toUpperCase());
  for (let i = 0; i < quantity; i++) {
    const name = labCode + (nextStrain + i);
    if (existing.indexOf(name.toUpperCase()) !== -1) {
      throw new Error(name + " already exists. Fix Next strain number on the Settings tab.");
    }
  }

  // Strain type: next allele / transgene number
  const typeName = read(workbook, "NS_Type");
  const types = table(workbook, "TypeTable");
  let typeRow = -1;
  let abbrev = "";
  let nextType = 0;
  if (typeName) {
    const typeNames = columnValues(types, "Type");
    typeRow = typeNames.indexOf(typeName);
    if (typeRow === -1) throw new Error("Unknown strain type: " + typeName);
    abbrev = columnValues(types, "Abbreviation")[typeRow];
    nextType = Number(columnValues(types, "Next number")[typeRow]);
    if (!(nextType > 0)) throw new Error("The next number for " + typeName + " (Settings tab) is not a number.");
  }

  const geno = read(workbook, "NS_Alleles");
  const now = excelNow();
  const rows: (string | number)[][] = [];
  const names: string[] = [];
  const alleles: string[] = [];
  for (let i = 0; i < quantity; i++) {
    const name = labCode + (nextStrain + i);
    let actualGeno = geno;
    if (typeName) {
      const allele = alleleCode + abbrev + (nextType + i);
      alleles.push(allele);
      actualGeno = allele + (geno ? "; " + geno : "");
    }
    names.push(name);
    rows.push(rowByHeaders(strains, {
      "Strain number": name,
      "Alleles / arrays": actualGeno,
      "Strain background": read(workbook, "NS_Background"),
      "DNA on array": read(workbook, "NS_DNA"),
      "Record date": now,
      "Notes and generation info": read(workbook, "NS_Notes"),
      "Maintenance info": read(workbook, "NS_Maintenance"),
      "Generated by / obtained from": author,
      "Publicly available?": read(workbook, "NS_Available"),
      "Box location": read(workbook, "NS_Location"),
    }));
  }
  appendRows(strains, rows);

  // Raise the next numbers
  named(workbook, "NextStrain").setValue(nextStrain + quantity);
  if (typeName) {
    column(types, "Next number")
      .getCell(typeRow, 0).setValue(nextType + quantity);
  }
  return "Added " + names.join(", ") + (alleles.length ? " with " + alleles.join(", ") : "") + ".";
}

// ---------- helpers (the same in every script) ----------
function named(workbook: ExcelScript.Workbook, name: string): ExcelScript.Range {
  const item = workbook.getNamedItem(name);
  if (!item) throw new Error('The name "' + name + '" is missing. Use the template workbook.');
  return item.getRange();
}

function table(workbook: ExcelScript.Workbook, name: string): ExcelScript.Table {
  const t = workbook.getTable(name);
  if (!t) throw new Error('The table "' + name + '" is missing. Use the template workbook.');
  return t;
}

function column(t: ExcelScript.Table, header: string): ExcelScript.Range {
  const c = t.getColumnByName(header);
  if (!c) throw new Error('The column "' + header + '" is missing. Keep the column names as they are.');
  return c.getRangeBetweenHeaderAndTotal();
}

function read(workbook: ExcelScript.Workbook, name: string): string {
  const value = named(workbook, name).getValue();
  return value === null || value === undefined ? "" : String(value).trim();
}

function clearForm(workbook: ExcelScript.Workbook, names: string[]) {
  names.forEach(n => named(workbook, n).setValue(""));
}

function columnValues(t: ExcelScript.Table, header: string): string[] {
  return column(t, header).getValues().map(r => String(r[0]).trim());
}

// A table row as a list, in the table's column order
function rowByHeaders(table: ExcelScript.Table, values: { [header: string]: string | number }): (string | number)[] {
  const headers = table.getHeaderRowRange().getValues()[0].map(h => String(h));
  return headers.map(h => (values[h] === undefined ? "" : values[h]));
}

// Adds rows at the bottom of a table. A new table starts with one empty row: fill that first.
function appendRows(table: ExcelScript.Table, rows: (string | number)[][]) {
  const body = table.getRangeBetweenHeaderAndTotal();
  const first = body.getValues();
  if (table.getRowCount() === 1 && first[0].every(v => String(v) === "")) {
    body.setValues([rows[0]]);
    rows = rows.slice(1);
  }
  if (rows.length) table.addRows(-1, rows);
}

// Now as an Excel date number, with the time (so same-day rows still sort in order)
function excelNow(): number {
  const d = new Date();
  return (d.getTime() - d.getTimezoneOffset() * 60000) / 86400000 + 25569;
}
