// Set up a blank workbook for the strain collection
// Run once in an empty workbook. It creates the Forms, Strains, Requests, Prefixes and Settings
// tabs, the tables, the dropdowns and the named cells the other scripts use.
// Change the values below for your lab first (you can also change them later on the Settings tab).
const LAB = {
  labName: "Wontakal",
  labCode: "REC",        // strains become REC1, REC2...
  alleleCode: "vrt",     // alleles become vrt1, transgenes vrtEx1...
  firstStrainNumber: 1,
  notifyEmails: "",      // e.g. "manager@university.edu, you@university.edu"
  // [name, abbreviation, first number]
  strainTypes: [["Allele", "", 1], ["Single insertion", "Si", 1], ["Array", "Ex", 1],
    ["Integrant", "Is", 1], ["Deficiency", "Df", 1], ["Transposon", "Ti", 1]] as (string | number)[][],
};

const STRAIN_HEADERS = ["Strain number", "Alleles / arrays", "Strain background", "DNA on array", "Record date",
  "Notes and generation info", "Maintenance info", "Generated by / obtained from",
  "Publicly available?", "Box location", "# of vials"];
const STRAIN_WIDTHS = [80, 200, 100, 170, 75, 280, 190, 135, 80, 90, 55];
const COLORS = { teal: "#2C5F6E", pale: "#EEF4F5", ink: "#3B4D52", hint: "#6B7B80", border: "#9FBCC3", result: "#E6F4EA" };

function main(workbook: ExcelScript.Workbook) {
  const existing = ["Forms", "Strains", "Requests", "Prefixes", "Settings"].filter(n => workbook.getWorksheet(n));
  if (existing.length) {
    throw new Error("This workbook already has: " + existing.join(", ") + ". Run the setup in a new, empty workbook.");
  }
  const first = workbook.getWorksheets()[0];
  setupSettings(workbook);
  setupTables(workbook);
  setupForms(workbook);
  // Remove the empty "Sheet1" a new workbook starts with
  if (first && ["Forms", "Strains", "Requests", "Prefixes", "Settings"].indexOf(first.getName()) === -1) {
    const used = first.getUsedRange(true);
    if (!used || used.getValues().every(r => r.every(v => v === ""))) first.delete();
  }
  workbook.getWorksheet("Forms")?.activate();
}

// ---------- Settings: lab codes, next strain number, strain types ----------
function setupSettings(workbook: ExcelScript.Workbook) {
  const s = workbook.addWorksheet("Settings");
  s.getRange("A1").setValue("Settings");
  s.getRange("A1").getFormat().getFont().setSize(14);
  s.getRange("A1").getFormat().getFont().setBold(true);
  s.getRange("A1").getFormat().getFont().setColor(COLORS.teal);
  s.getRange("A2").setValue("Change the white cells. The scripts read these values by name.");
  hint(s.getRange("A2"));
  const rows: [string, string | number, string, string][] = [
    ["Lab name", LAB.labName, "LabName", ""],
    ["Lab code", LAB.labCode, "LabCode", "Strains become " + LAB.labCode + "1, " + LAB.labCode + "2..."],
    ["Allele code", LAB.alleleCode, "AlleleCode", "Alleles become " + LAB.alleleCode + "1; transgenes " + LAB.alleleCode + "Si1, " + LAB.alleleCode + "Ex1..."],
    ["Next strain number", LAB.firstStrainNumber, "NextStrain", "The number the next strain gets. Raised automatically."],
    ["Email people about new requests", LAB.notifyEmails, "NotifyEmails", "Work emails, separated by commas. They are @mentioned in a comment, which emails them."],
  ];
  rows.forEach((r, i) => {
    const row = 4 + i;
    label(s.getRange("A" + row), r[0]);
    s.getRange("A" + row).getFormat().getFill().setColor(COLORS.pale);
    const box = s.getRange("B" + row);
    box.setValue(r[1]);
    inputBox(box);
    box.getFormat().getFont().setBold(true);
    s.getRange("C" + row).setValue(r[3]);
    hint(s.getRange("C" + row));
    workbook.addNamedItem(r[2], box);
  });
  label(s.getRange("A11"), "Strain types (the form offers these; Next number is raised automatically)");
  const n = LAB.strainTypes.length;
  s.getRange("A12:C12").setValues([["Type", "Abbreviation", "Next number"]]);
  s.getRange("A13:C" + (12 + n)).setValues(LAB.strainTypes);
  const types = s.addTable("A12:C" + (12 + n), true);
  types.setName("TypeTable");
  types.setPredefinedTableStyle("TableStyleLight9");
  s.getRange("A:A").getFormat().setColumnWidth(200);
  s.getRange("B:B").getFormat().setColumnWidth(190);
  s.getRange("C:C").getFormat().setColumnWidth(420);
}

// ---------- Strains, Requests, Prefixes tables ----------
function setupTables(workbook: ExcelScript.Workbook) {
  const strains = makeTable(workbook, "Strains", "StrainTable", STRAIN_HEADERS, STRAIN_WIDTHS);
  strains.getColumnByName("Record date")?.getRangeBetweenHeaderAndTotal().setNumberFormat("yyyy-mm-dd");

  const reqHeaders = ["Requested by", "Request date", "Returned?"].concat(STRAIN_HEADERS, ["Source", "Order link", "WormBase"]);
  const requests = makeTable(workbook, "Requests", "RequestTable", reqHeaders, [100, 80, 70].concat(STRAIN_WIDTHS, [75, 110, 85]));
  requests.getColumnByName("Request date")?.getRangeBetweenHeaderAndTotal().setNumberFormat("yyyy-mm-dd");
  requests.getColumnByName("Record date")?.getRangeBetweenHeaderAndTotal().setNumberFormat("yyyy-mm-dd");
  // Returned?: yes / no dropdown, red while a strain is out, green once it is back
  const returned = workbook.getWorksheet("Requests")!.getRange("C2:C2000");
  returned.getDataValidation().setRule({ list: { inCellDropDown: true, source: "no,yes" } });
  const out = returned.addConditionalFormat(ExcelScript.ConditionalFormatType.containsText).getTextComparison();
  out.setRule({ operator: ExcelScript.ConditionalTextOperator.beginsWith, text: "no" });
  out.getFormat().getFill().setColor("#F4CCCC");
  out.getFormat().getFont().setColor("#990000");
  const back = returned.addConditionalFormat(ExcelScript.ConditionalFormatType.containsText).getTextComparison();
  back.setRule({ operator: ExcelScript.ConditionalTextOperator.beginsWith, text: "yes" });
  back.getFormat().getFill().setColor("#D9EAD3");
  back.getFormat().getFont().setColor("#274E13");

  const prefixes = makeTable(workbook, "Prefixes", "PrefixTable",
    ["Prefix", "Lab / person", "Added", "Note", "Start numbering at"], [60, 170, 80, 230, 110]);
  prefixes.getRangeBetweenHeaderAndTotal().setValues([[LAB.labCode, "Our lab", "", "Our own strains", 1]]);
  prefixes.getColumnByName("Added")?.getRangeBetweenHeaderAndTotal().setNumberFormat("yyyy-mm-dd");
}

function makeTable(workbook: ExcelScript.Workbook, sheetName: string, tableName: string,
  headers: string[], widths: number[]): ExcelScript.Table {
  const s = workbook.addWorksheet(sheetName);
  const last = columnLetter(headers.length);
  s.getRange("A1:" + last + "1").setValues([headers]);
  const t = s.addTable("A1:" + last + "2", true);
  t.setName(tableName);
  t.setPredefinedTableStyle("TableStyleMedium2");
  const header = t.getHeaderRowRange();
  header.getFormat().setWrapText(true);
  header.getFormat().setRowHeight(32);
  header.getFormat().setVerticalAlignment(ExcelScript.VerticalAlignment.center);
  s.getRange("A2:" + last + "2000").getFormat().setWrapText(true);
  s.getRange("A2:A2000").getFormat().getFont().setBold(true);
  widths.forEach((w, i) => s.getRange(columnLetter(i + 1) + ":" + columnLetter(i + 1)).getFormat().setColumnWidth(w));
  s.getFreezePanes().freezeRows(1);
  return t;
}

// ---------- Forms tab: four sections, each read by one script ----------
type Field = { label: string, name?: string, hint?: string, value?: string | number, formula?: string, list?: string, tall?: boolean };

function setupForms(workbook: ExcelScript.Workbook) {
  const f = workbook.addWorksheet("Forms");
  f.setPosition(0);
  f.setShowGridlines(false);
  f.getRange("A:A").getFormat().setColumnWidth(210);
  f.getRange("B:B").getFormat().setColumnWidth(290);
  f.getRange("C:C").getFormat().setColumnWidth(380);
  f.getRange("A1").setValue("Strain collection forms");
  f.getRange("A1").getFormat().getFont().setSize(14);
  f.getRange("A1").getFormat().getFont().setBold(true);
  f.getRange("A1").getFormat().getFont().setColor(COLORS.teal);
  f.getRange("A2").setValue("Fill in a section, then click its button (or run the script from the Automate tab). The result appears in the green line under the section.");
  hint(f.getRange("A2"));

  let row = 4;
  // Each field returns its row, so later formulas can point at it (B + row)
  const section = (title: string, script: string, fields: (rows: number[]) => Field[], resultName: string) => {
    const bar = f.getRange("A" + row + ":C" + row);
    bar.getFormat().getFill().setColor(COLORS.teal);
    bar.getFormat().getFont().setColor("#FFFFFF");
    bar.getFormat().getFont().setBold(true);
    bar.getFormat().setRowHeight(24);
    f.getRange("A" + row).setValue(title);
    f.getRange("C" + row).setValue("Button / script: " + script);
    row++;
    const rows: number[] = [];
    // Fields can refer to earlier fields' rows: build them one at a time
    for (let i = 0; ; i++) {
      const list = fields(rows);
      if (i >= list.length) break;
      const fd = list[i];
      rows.push(row);
      label(f.getRange("A" + row), fd.label);
      const cell = f.getRange("B" + row);
      if (fd.formula) {
        cell.setFormula(fd.formula);
        cell.getFormat().getFill().setColor(COLORS.pale);
        cell.getFormat().getFont().setBold(true);
        cell.getFormat().getFont().setColor(COLORS.teal);
      } else {
        if (fd.value !== undefined) cell.setValue(fd.value);
        inputBox(cell);
      }
      cell.getFormat().setWrapText(true);
      cell.getFormat().setHorizontalAlignment(ExcelScript.HorizontalAlignment.left);
      if (fd.list) cell.getDataValidation().setRule({ list: { inCellDropDown: true, source: fd.list } });
      if (fd.name) workbook.addNamedItem(fd.name, cell);
      if (fd.hint) { f.getRange("C" + row).setValue(fd.hint); hint(f.getRange("C" + row)); }
      f.getRange("A" + row + ":C" + row).getFormat().setRowHeight(fd.tall ? 36 : 22);
      row++;
    }
    label(f.getRange("A" + row), "Result");
    const result = f.getRange("B" + row + ":C" + row);
    result.merge(false);
    result.getFormat().getFill().setColor(COLORS.result);
    result.getFormat().getFont().setBold(true);
    result.getFormat().getFont().setColor("#1E6B34");
    result.getFormat().setWrapText(true);
    result.getFormat().setRowHeight(30);
    workbook.addNamedItem(resultName, f.getRange("B" + row));
    row += 2;
  };

  section("1. Create a new strain from your own lab", "CreateNewStrain", r => [
    { label: "Number of strains to create at once", name: "NS_Quantity", hint: "Up to 100 at once", value: 1 },
    { label: "Strain type", name: "NS_Type", hint: "Leave empty if you only need the new strain number", list: '=INDIRECT("TypeTable[Type]")' },
    { label: "New strain number", hint: "Preview. Numbers are given when you click the button.",
      formula: `=LabCode&NextStrain&IF(B${r[0]}>1," to "&LabCode&(NextStrain+B${r[0]}-1),"")` },
    { label: "New allele / transgene name", hint: "Preview. Added in front of Alleles / arrays.",
      formula: `=IF(B${r[1]}="","",AlleleCode&INDEX(TypeTable[Abbreviation],MATCH(B${r[1]},TypeTable[Type],0))&INDEX(TypeTable[Next number],MATCH(B${r[1]},TypeTable[Type],0)))` },
    { label: "Alleles / arrays", name: "NS_Alleles", hint: "unc-3(e151) X" },
    { label: "Strain background", name: "NS_Background", hint: "him-5 or pha-1 for example" },
    { label: "Generated by", name: "NS_GeneratedBy", hint: "Required. your name; X lab or CGC / your name" },
    { label: "DNA on array", name: "NS_DNA", hint: "myo-2prom::GFP" },
    { label: "Notes and generation info", name: "NS_Notes", hint: "CRISPR Mello method with guides X and Y", tall: true },
    { label: "Maintenance info", name: "NS_Maintenance", hint: "Grows at 15C." },
    { label: "Publicly available?", name: "NS_Available", hint: "CGC" },
    { label: "Box location", name: "NS_Location", hint: 'Only the strain manager should edit this. Must contain "box" to be requestable.' },
  ], "NS_Result");

  section("2. Add an existing strain (CGC / other labs)", "AddExistingStrain", r => [
    { label: "Comes from", name: "ES_Source", hint: "CGC, NBRP or Other lab", value: "CGC", list: "CGC,NBRP,Other lab" },
    { label: "Strain number", name: "ES_Name", hint: "For CGC / NBRP: its name, e.g. CB1370. For other labs: leave empty and pick a prefix." },
    { label: "CGC page", hint: "Open it to copy the genotype and details",
      formula: `=IF(AND(B${r[0]}="CGC",B${r[1]}<>""),HYPERLINK("https://cgc.umn.edu/strain/"&B${r[1]},"Open "&B${r[1]}&" on the CGC"),"")` },
    { label: "Prefix (other labs)", name: "ES_Prefix", hint: "e.g. OH. Add new ones in section 3.", list: '=INDIRECT("PrefixTable[Prefix]")' },
    { label: "Number (optional)", name: "ES_Number", hint: "Only to follow the lab's own numbering, e.g. 15903" },
    { label: "Name it will get", hint: "Preview. Confirmed when you click the button.",
      formula: `=IF(B${r[3]}="","",B${r[3]}&IF(B${r[4]}<>"",B${r[4]},MAX(IFERROR(INDEX(PrefixTable[Start numbering at],MATCH(B${r[3]},PrefixTable[Prefix],0)),1),` +
        `MAX(IF(LEFT(StrainTable[Strain number],LEN(B${r[3]}))=B${r[3]},IFERROR(--MID(StrainTable[Strain number],LEN(B${r[3]})+1,20),0),0))+1)))` },
    { label: "Name in the lab it came from", name: "ES_Original", hint: "Optional, saved in the notes, e.g. OH15432" },
    { label: "Alleles / arrays", name: "ES_Alleles", hint: "unc-3(e151) X" },
    { label: "Strain background", name: "ES_Background", hint: "him-5 or pha-1 for example" },
    { label: "Generated by", name: "ES_GeneratedBy", hint: "Required. your name; X lab or CGC / your name" },
    { label: "DNA on array", name: "ES_DNA", hint: "myo-2prom::GFP" },
    { label: "Notes and generation info", name: "ES_Notes", hint: "Description from the CGC page, for example", tall: true },
    { label: "Maintenance info", name: "ES_Maintenance", hint: "Grows at 15C." },
    { label: "Publicly available?", name: "ES_Available", hint: 'Left empty, it is set to CGC / NBRP from "Comes from"' },
    { label: "Box location", name: "ES_Location", hint: 'Must contain "box" to be requestable.' },
  ], "ES_Result");

  section("3. Create a new prefix for strains from another lab", "AddPrefix", r => [
    { label: "New prefix", name: "NP_Prefix", hint: "1-5 letters, e.g. SH" },
    { label: "Whose prefix is it?", name: "NP_Owner", hint: "Full name or lab, e.g. Sumin Hong" },
    { label: "Start numbering at", name: "NP_Start", hint: "e.g. 15903 if that lab's strains already go up to OH15902", value: 1 },
    { label: "Check the CGC lab codes", hint: "Is it an official CGC lab code? Only use it if you are in that lab.",
      formula: `=IF(B${r[0]}="","",HYPERLINK("https://cgc.umn.edu/laboratory/"&UPPER(B${r[0]}),"Open the CGC page for "&UPPER(B${r[0]})))` },
  ], "NP_Result");

  section("4. Request a strain from the collection", "RequestStrain", r => [
    { label: "Strain", name: "RQ_Strain", hint: "Pick or type the strain number", list: '=INDIRECT("StrainTable[Strain number]")' },
    { label: "Box location", hint: "From the Strains tab",
      formula: `=IF(B${r[0]}="","",IFERROR(INDEX(StrainTable[Box location],MATCH(B${r[0]},StrainTable[Strain number],0))&"","not in the collection"))` },
    { label: "Is it out right now?", hint: "From the Requests tab",
      formula: `=IF(B${r[0]}="","",IF(COUNTIFS(RequestTable[Strain number],B${r[0]},RequestTable[Returned?],"no")>0,"Yes, not returned yet","No, available"))` },
    { label: "Your name", name: "RQ_Name" },
  ], "RQ_Result");
}

// ---------- small formatting helpers ----------
function label(range: ExcelScript.Range, text: string) {
  range.setValue(text);
  range.getFormat().getFont().setBold(true);
  range.getFormat().getFont().setColor(COLORS.ink);
  range.getFormat().setWrapText(true);
  range.getFormat().setVerticalAlignment(ExcelScript.VerticalAlignment.center);
}

function hint(range: ExcelScript.Range) {
  range.getFormat().getFont().setItalic(true);
  range.getFormat().getFont().setSize(9);
  range.getFormat().getFont().setColor(COLORS.hint);
}

function inputBox(range: ExcelScript.Range) {
  range.getFormat().getFill().setColor("#FFFFFF");
  [ExcelScript.BorderIndex.edgeTop, ExcelScript.BorderIndex.edgeBottom, ExcelScript.BorderIndex.edgeLeft,
    ExcelScript.BorderIndex.edgeRight].forEach(edge => {
      const b = range.getFormat().getRangeBorder(edge);
      b.setStyle(ExcelScript.BorderLineStyle.continuous);
      b.setColor(COLORS.border);
    });
}

function columnLetter(n: number): string {
  let s = "";
  for (; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + (n - 1) % 26) + s;
  return s;
}
