// Add an existing strain (CGC / NBRP / another lab)
// Reads section 2 of the Forms tab. With a prefix (e.g. OH), the strain gets the next free
// number for it (OH1075), or the number typed in "Number" to follow that lab's numbering.
function main(workbook: ExcelScript.Workbook) {
  const result = named(workbook, "ES_Result");
  try {
    result.setValue("✓ " + addStrain(workbook));
    clearForm(workbook, ["ES_Name", "ES_Prefix", "ES_Number", "ES_Original", "ES_Alleles", "ES_Background",
      "ES_DNA", "ES_Notes", "ES_Maintenance", "ES_Available", "ES_Location"]);
  } catch (e) {
    const reason = String(e).replace(/^Error: /, "");
    result.setValue("✗ " + reason);
    // Also fail the run, so the Automate pane / button shows the reason instead of "complete"
    throw new Error(reason);
  }
}

function addStrain(workbook: ExcelScript.Workbook): string {
  const source = read(workbook, "ES_Source") || "CGC";
  // A prefix only applies to strains from another lab
  const prefix = source === "Other lab" ? read(workbook, "ES_Prefix").toUpperCase() : "";
  const typedNumber = read(workbook, "ES_Number");
  const author = read(workbook, "ES_GeneratedBy");
  if (!author) throw new Error("Fill in Generated by.");

  const strains = table(workbook, "StrainTable");
  const names = columnValues(strains, "Strain number");
  let name = read(workbook, "ES_Name");
  if (prefix) {
    const prefixes = columnValues(table(workbook, "PrefixTable"), "Prefix").map(p => p.toUpperCase());
    const at = prefixes.indexOf(prefix);
    if (at === -1) throw new Error(prefix + " is not in the prefix list. Create it in section 3 first.");
    if (typedNumber) {
      const n = Number(typedNumber);
      if (!(n > 0) || Math.floor(n) !== n) throw new Error("Number must be a whole number above 0.");
      name = prefix + n;
    } else {
      const start = Number(columnValues(table(workbook, "PrefixTable"), "Start numbering at")[at]) || 1;
      name = prefix + Math.max(lastNumberForPrefix(prefix, names) + 1, start);
    }
  }
  if (!name) throw new Error("Type the strain number, or pick a prefix for a strain from another lab.");
  if (names.some(n => n.toUpperCase() === name.toUpperCase())) {
    throw new Error(name + " is already in the collection. Use a different name.");
  }

  let notes = read(workbook, "ES_Notes");
  const original = read(workbook, "ES_Original");
  if (original) notes = "Original name: " + original + (notes ? ". " + notes : "");
  let available = read(workbook, "ES_Available");
  // Keeps where it came from, so a later request knows where to order it
  if (!available && (source === "CGC" || source === "NBRP")) available = source;

  appendRows(strains, [rowByHeaders(strains, {
    "Strain number": name,
    "Alleles / arrays": read(workbook, "ES_Alleles"),
    "Strain background": read(workbook, "ES_Background"),
    "DNA on array": read(workbook, "ES_DNA"),
    "Record date": excelNow(),
    "Notes and generation info": notes,
    "Maintenance info": read(workbook, "ES_Maintenance"),
    "Generated by / obtained from": author,
    "Publicly available?": available,
    "Box location": read(workbook, "ES_Location"),
  })]);
  return "Added " + name + ".";
}

// Highest number used with this exact prefix (SH matches SH1008, not SHA12), or 0
function lastNumberForPrefix(prefix: string, names: string[]): number {
  const re = new RegExp("^" + prefix + "(\\d+)$", "i");
  let max = 0;
  names.forEach(n => {
    const m = n.match(re);
    if (m) max = Math.max(max, parseInt(m[1], 10));
  });
  return max;
}

// ---------- helpers (the same in every script) ----------
function named(workbook: ExcelScript.Workbook, name: string): ExcelScript.Range {
  const item = workbook.getNamedItem(name);
  if (!item) throw new Error('The name "' + name + '" is missing. Use the template workbook.');
  return item.getRange();
}

function table(workbook: ExcelScript.Workbook, name: string): ExcelScript.Table {
  const t = workbook.getTable(name);
  if (!t) throw new Error('The table "' + name + '" is missing. Use the template workbook.');
  return t;
}

function column(t: ExcelScript.Table, header: string): ExcelScript.Range {
  const c = t.getColumnByName(header);
  if (!c) throw new Error('The column "' + header + '" is missing. Keep the column names as they are.');
  return c.getRangeBetweenHeaderAndTotal();
}

function read(workbook: ExcelScript.Workbook, name: string): string {
  const value = named(workbook, name).getValue();
  return value === null || value === undefined ? "" : String(value).trim();
}

function clearForm(workbook: ExcelScript.Workbook, names: string[]) {
  names.forEach(n => named(workbook, n).setValue(""));
}

function columnValues(t: ExcelScript.Table, header: string): string[] {
  return column(t, header).getValues().map(r => String(r[0]).trim());
}

// A table row as a list, in the table's column order
function rowByHeaders(table: ExcelScript.Table, values: { [header: string]: string | number }): (string | number)[] {
  const headers = table.getHeaderRowRange().getValues()[0].map(h => String(h));
  return headers.map(h => (values[h] === undefined ? "" : values[h]));
}

// Adds rows at the bottom of a table. A new table starts with one empty row: fill that first.
function appendRows(table: ExcelScript.Table, rows: (string | number)[][]) {
  const body = table.getRangeBetweenHeaderAndTotal();
  const first = body.getValues();
  if (table.getRowCount() === 1 && first[0].every(v => String(v) === "")) {
    body.setValues([rows[0]]);
    rows = rows.slice(1);
  }
  if (rows.length) table.addRows(-1, rows);
}

// Now as an Excel date number, with the time (so same-day rows still sort in order)
function excelNow(): number {
  const d = new Date();
  return (d.getTime() - d.getTimezoneOffset() * 60000) / 86400000 + 25569;
}
